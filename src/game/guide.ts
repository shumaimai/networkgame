/** 本店と支店(ルーター・スイッチ・PCが1台ずつ)。回線と拠点間の配線は、呼び出した側でつなぐ */
function twoSites(inetModel: string) {
  const b = new Builder();
  const inet = at(b.add(inetModel, 'inet', 'インターネット', 'fixed'), inetModel === 'internet' ? 480 : 760, 90);
  const mk = (key: string, label: string, net: string, x: number) => {
    const rt = at(b.add('router', key + 'rt', `${label}ルーター`), x, 270), sw = at(b.add('l2-5', key + 'sw', `${label}スイッチ`), x, 440);
    const pc = at(host(b.add('pc', key + 'pc', `${label}PC`, 'supplied'), `${net}.11`, `${net}.1`, '8.8.8.8'), x, 630);
    (rt.cfg as GwCfg).lan[0].ip = `${net}.1`;
    b.link(rt, 1, sw, 0); b.plug(pc, sw);
    return { rt, sw, pc };
  };
  return { b, inet, a: mk('a', '本店', '192.168.10', 480), z: mk('z', '支店', '192.168.20', 1040) };
}

