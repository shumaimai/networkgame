const at = (d: Device, x: number, y: number): Device => { d.x = x; d.y = y; return d; };
const host = (d: Device, ip: string, gw = '', dns = ''): Device => { Object.assign(d.cfg, { ip, gw, dns }); return d; };
const ip = (s: string) => parseIp(s)!;

function lan(): { b: Builder; a: Device } {
  const b = new Builder();
  const a = at(host(b.add('pc', 'a', 'PC-A', 'supplied'), '192.168.1.10'), 480, 520), c = at(host(b.add('pc', 'c', 'PC-B', 'supplied'), '192.168.1.11'), 920, 520);
  const sw = at(b.add('l2-5', 'sw', 'スイッチ'), 700, 300);
  b.plug(a, sw); b.plug(c, sw);
  return { b, a };
}
function wan(): { b: Builder; pc: Device; sw: Device; rt: Device } {
  const b = new Builder();
  const inet = at(b.add('internet', 'inet', 'インターネット', 'fixed'), 700, 90);
  const rt = at(b.add('router', 'rt', 'ルーター'), 700, 250), sw = at(b.add('l2-5', 'sw', 'スイッチ'), 700, 420);
  const pc = at(host(b.add('pc', 'a', 'PC', 'supplied'), '192.168.1.10', '192.168.1.1', '8.8.8.8'), 520, 620);
  b.link(inet, 0, rt, 0); b.link(rt, 1, sw, 0); b.plug(pc, sw);
  (rt.cfg as GwCfg).lan[0].ip = '192.168.1.1';
  return { b, pc, sw, rt };
}
